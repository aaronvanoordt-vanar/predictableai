const make = (category: RecipeCategory, kind: DetectorKind, b: Base, for_who: string, titles: string[], config: Record<string, unknown>): RadarRecipe =>
  ({ id: b[0], category, kind, weight: b[1], name: b[2], for_who, rationale: b[3], decision_maker_titles: titles, config });

const news = (c: RecipeCategory, b: Base, f: string, t: string[], queries: string[], window_days = 30, sources: string[] = PRESS) =>
  make(c, "news", b, f, t, { queries, sources, window_days });
