/**
 * _shared/radar-recipes-telco.ts — recetas de la biblioteca del Radar para
 * quien vende conectividad a empresas (2026-11-17, pedido del dueño para
 * Claro Empresas: internet dedicado, enlaces de datos, SD-WAN, telefonía,
 * móvil corporativo, nube y seguridad).
 *
 * La pregunta de cada receta es la misma: ¿qué hecho OBSERVABLE delata que
 * esta empresa va a contratar, cambiar o ampliar su conectividad? Cinco
 * familias:
 *   telco_pain      cortes, quejas y el proveedor que tiene hoy
 *   telco_sites     sedes nuevas, mudanzas y crecimiento (cada sede = un enlace)
 *   telco_digital   nube, migraciones y operación que depende de la red
 *   telco_verticals sectores donde la conectividad es crítica
 *   telco_public    licitaciones y contratos del sector público
 *
 * Lo que NO se puede ver desde afuera no se promete: cuánto paga una empresa
 * privada por su plan no es público. Las recetas de «plan caro» usan lo que sí
 * lo es (montos de contratos públicos, alzas de tarifas anunciadas, telefonía
 * y correo heredados, planes de recorte de costos) y lo dicen en su texto.
 *
 * Las consultas nombran a los operadores que compiten con quien vende; quien
 * use una receta siendo otro operador edita la consulta en su detector.
 * Todas pasan por normalizeDetector() en deno test (radar-footprint.test.ts).
 */

