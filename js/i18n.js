    'Secuencias': 'Sequences',
    'Generador de mensajes IA': 'AI message generator',
    'Inbox WhatsApp': 'WhatsApp Inbox',
    'Plantillas': 'Templates',
    'Ventas AI': 'Sales AI',
    'Reportes': 'Reports',
    'Mi rendimiento': 'My performance',
    // Sidebar — footer
    'Primeros pasos': 'Getting started',
    'Claro': 'Light',
    'Oscuro': 'Dark',
    'Ajustes': 'Settings',
    'Cerrar sesión': 'Log out',
    // Dashboard — KPIs
    'Reuniones generadas': 'Meetings booked',
    'Marcadas con «Reunión conseguida» en el Inbox o el CRM': 'Marked as "Meeting booked" from the Inbox or the CRM',
