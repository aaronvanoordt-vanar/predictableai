/**
 * js/i18n.js — Interruptor de idioma ES/EN para la interfaz principal
 * ─────────────────────────────────────────────────────────────────────────────
 * Primera iteración honesta del switch de idioma: traduce el "chrome" de la
 * app (sidebar, dashboard y encabezados de Ajustes) mediante un diccionario de
 * strings exactos. El español es el idioma fuente (los textos viven
 * hardcodeados en HTML/JS), así que en ES no se toca nada; en EN se reemplazan
 * los nodos de texto cuyo contenido coincide con el diccionario.
 *
 * Las vistas profundas (Prospección, Inbox, Coach…) siguen en español hasta
 * que se extraigan sus strings — el toggle deja la preferencia lista en
 * localStorage ('predictable_lang') para esa siguiente fase.
 *
 * API pública: window.i18n = { get(), set(lang), apply() }
 */
